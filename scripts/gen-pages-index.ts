import fs from 'node:fs';
import path from 'node:path';

/** Writes pages/index.ts: every page class under pages/NN-<module>/, in module order, as a lazy fixture. */
const ROOT = path.resolve(__dirname, '..');
const PAGES = path.join(ROOT, 'pages');

const entries: { key: string; cls: string; spec: string }[] = [];
for (const dir of fs.readdirSync(PAGES).filter((d) => /^\d{2}-/.test(d)).sort()) {
  for (const file of fs.readdirSync(path.join(PAGES, dir)).filter((f) => f.endsWith('.ts')).sort()) {
    const src = fs.readFileSync(path.join(PAGES, dir, file), 'utf8');
    const cls = /export class (\w+) extends BasePage/.exec(src)?.[1];
    if (!cls) continue;
    const base = cls.replace(/Page$/, '');
    const key = `${base.charAt(0).toLowerCase()}${base.slice(1)}${cls.endsWith('Page') && cls !== 'BottomNavPage' ? 'Page' : ''}`;
    entries.push({ key: cls === 'BottomNavPage' ? 'bottomNav' : key, cls, spec: `@madark/pages/${dir}/${file.replace(/\.ts$/, '')}` });
  }
}

const out = `${entries.map((e) => `import { ${e.cls} } from '${e.spec}';`).join('\n')}

/**
 * Generated by scripts/gen-pages-index.ts — do not edit. Every page object, in module order.
 * Fixture keys are the names below; specs get them lazily (a page is constructed when a test uses it).
 */
export const PAGES = {
${entries.map((e) => `  ${e.key}: ${e.cls},`).join('\n')}
} as const;

export type Pages = { [K in keyof typeof PAGES]: InstanceType<(typeof PAGES)[K]> };

export function lazyPages(): Pages {
  const out = {} as Pages;
  const cache = new Map<string, unknown>();
  for (const [key, Page] of Object.entries(PAGES)) {
    Object.defineProperty(out, key, {
      enumerable: true,
      get() {
        if (!cache.has(key)) cache.set(key, new (Page as new () => unknown)());
        return cache.get(key);
      },
    });
  }
  return out;
}
`;
fs.writeFileSync(path.join(PAGES, 'index.ts'), out);
process.stdout.write(`pages/index.ts: ${entries.length} pages\n`);
